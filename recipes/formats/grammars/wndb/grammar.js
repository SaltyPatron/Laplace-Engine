// Princeton wndb(5), senseidx(5), wninput(5), and the .vrb sentence files.
// External tokens enforce the counts the source writes; all record structure
// and named fields remain in the generated Tree-sitter parser.
module.exports = grammar({
  name: 'wndb',
  extras: $ => [/[ \t]/],
  externals: $ => [
    $._data_start, $._index_start, $._sense_start, $._exc_start,
    $._frame_start, $._sentidx_start, $._header_start,
    $._data_pos, $._word_count, $._word, $.words_end,
    $._pointer_count, $._pointer_symbol, $.pointers_end,
    $._frame_count, $._frame_plus, $.frames_end, $._nonverb,
    $._index_count, $._index_pointer_count, $._index_pointer_symbol,
    $.index_pointers_end, $._index_sense_count, $._index_tag_count,
    $._index_offset, $.index_end
  ],
  rules: {
    document: $ => repeat(choice($.header, $.synset_record, $.index_record,
      $.sense_record, $.exc_record, $.frame_record, $.sentidx_record, $._newline)),
    header: $ => seq($._header_start, $.header_text),
    header_text: $ => /[^\r\n]+/,
    synset_record: $ => seq($._data_start,
      field('synset_offset', alias($._offset, $.field)),
      field('lex_filenum', alias(/[0-9]{2}/, $.field)),
      field('ss_type', alias($._data_pos, $.field)),
      field('w_cnt', alias($._word_count, $.field)), repeat($.word), $.words_end,
      field('p_cnt', alias($._pointer_count, $.field)), repeat($.pointer), $.pointers_end,
      choice($._nonverb, $.frames), '|', optional(field('gloss', $.gloss))),
    word: $ => seq(field('word', alias($._word, $.field)),
      field('lex_id', alias(/[0-9a-fA-F]+/, $.field))),
    pointer: $ => seq(field('pointer_symbol', alias($._pointer_symbol, $.field)),
      field('target', alias($._offset, $.field)), field('pos', alias(/[nvars]/, $.field)),
      field('source_target', alias(/[0-9a-fA-F]{4}/, $.field))),
    frames: $ => seq(field('f_cnt', alias($._frame_count, $.field)), repeat($.frame), $.frames_end),
    frame: $ => seq(field('plus', alias($._frame_plus, $.field)),
      field('f_num', alias(/[0-9]{2}/, $.field)), field('w_num', alias(/[0-9a-fA-F]{2}/, $.field))),
    gloss: $ => /[^\r\n]+/,
    index_record: $ => seq($._index_start, field('lemma', alias($._token, $.field)),
      field('pos', alias(/[nvars]/, $.field)), field('synset_cnt', alias($._index_count, $.field)),
      field('p_cnt', alias($._index_pointer_count, $.field)), repeat($.index_pointer), $.index_pointers_end,
      field('sense_cnt', alias($._index_sense_count, $.field)),
      field('tagsense_cnt', alias($._index_tag_count, $.field)),
      repeat(field('synset_offset', alias($._index_offset, $.field))), $.index_end),
    index_pointer: $ => field('ptr_symbol', alias($._index_pointer_symbol, $.field)),
    sense_record: $ => seq($._sense_start, field('sense_key', alias($._token, $.field)),
      field('synset_offset', alias($._offset, $.field)), field('sense_number', alias($._decimal, $.field)),
      field('tag_cnt', alias($._decimal, $.field))),
    exc_record: $ => seq($._exc_start, field('inflected', alias($._token, $.field)),
      repeat1(field('lemma', alias($._token, $.field)))),
    frame_record: $ => seq($._frame_start, field('number', alias($._decimal, $.field)),
      field('text', $.gloss)),
    sentidx_record: $ => seq($._sentidx_start, field('sense_key', alias($._token, $.field)),
      optional(field('templates', alias(/[0-9]+(,[0-9]+)*/, $.field)))),
    _offset: $ => /[0-9]{8}/,
    _decimal: $ => /[0-9]+/,
    _token: $ => /[^ \t\r\n]+/,
    _newline: $ => choice('\n', '\r\n')
  }
});
